// Generates src/components/chat/katexCss.generated.ts: KaTeX's stylesheet with
// every font inlined as a woff2 data URI, so display maths renders identically
// on any device with no network and no font files to ship separately.
//
// Run after upgrading katex:  node scripts/build-katex-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const dist = dirname(require.resolve('katex/dist/katex.min.css'));
const { version } = JSON.parse(readFileSync(join(dist, '..', 'package.json'), 'utf8'));
let css = readFileSync(join(dist, 'katex.min.css'), 'utf8');

let fonts = 0;
css = css.replace(/src:url\(fonts\/([\w-]+)\.woff2\) format\("woff2"\)(?:,url\([^)]+\) format\("[^"]+"\))*/g, (_, name) => {
  fonts++;
  const data = readFileSync(join(dist, 'fonts', `${name}.woff2`)).toString('base64');
  return `src:url(data:font/woff2;base64,${data}) format("woff2")`;
});
if (fonts < 15 || /url\(fonts\//.test(css)) throw new Error(`font inlining failed (${fonts} fonts inlined)`);

const out = `// GENERATED by scripts/build-katex-css.mjs from katex@${version}. Do not edit.
// KaTeX (MIT) stylesheet with its ${fonts} fonts inlined as woff2 data URIs.
export const katexVersion = ${JSON.stringify(version)};
export const katexCss = ${JSON.stringify(css)};
`;
const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'components', 'chat', 'katexCss.generated.ts');
writeFileSync(target, out);
console.log(`katex@${version}: inlined ${fonts} fonts, ${(out.length / 1024).toFixed(0)} KB -> ${target}`);
